def clean_content_tags(content: str) -> str:
    """
    Remove meta-tags and markdown formatting often generated by LLMs 
    when outputting the condensed question.
    """
    if not content:
        return content
    
    # Parse the content inside the <output> tags
    if "<output>" in content and "</output>" in content:
        start_idx = content.find("<output>") + len("<output>")
        end_idx = content.find("</output>")
        if start_idx < end_idx:
            extracted_content = content[start_idx:end_idx].strip()
            if extracted_content:
                return extracted_content
    
    return content.strip()


def construct_research_problem(llm_client: LLMClient, research_field: str, research_background: str) -> str:
    """
    Construct a concise English research problem based on the given field and background.
    One-step generation: directly output a concise research problem without a separate condensation step.
    """
    prompt = f"""# Role
You are an experienced researcher with expertise in formulating concise research problem statements.

# Task
Based on the provided [Research Field] and [Research Background], write a concise research problem statement as a single coherent paragraph. The statement must naturally convey:
- The specific unsolved problem, limitation, or gap that needs to be addressed
- The relevant discipline and sub-field
- The current state of existing approaches and key challenges

# Output Format
Wrap the final statement inside <output> </output> tags. Rules for the content inside the tags:
- Write as a single paragraph of fluent, flowing prose
- Do NOT use bullet points, numbered lists, or section headers of any kind
- Include NO introductory phrases (e.g., "Here is the statement:", "Based on the background:")
- Include NO conversational filler or meta-commentary (e.g., "I have written...", "This statement covers...")
- Output only the statement itself, nothing else

# Input
[Research Field]:
{research_field}

[Research Background]:
{research_background}"""
    try:
        research_problem = llm_client.generate_response(prompt, max_tokens=1024, temperature=0.3)
        if not research_problem or not research_problem.strip():
            return ""
        return clean_content_tags(research_problem)
    except Exception as e:
        print(f"[Thread: {threading.get_ident()}] Error constructing research problem: {str(e)}", flush=True)
        return ""


def generate_reference_solution(llm_client: LLMClient, research_problem: str, raw_solution: str) -> str:
    """
    Generate a refined reference solution based on the research problem 
    and the original solution from the paper.
    The output must be faithful to the original, avoid fabricated details,
    exclude specific numerical results, and present the method 
    in an academic style.
    """
    prompt = f"""# Role
You are an experienced researcher tasked with writing a reference solution for a research problem. Your writing must be rigorous, academic in style, logically structured, and concise.

# Task
Based on the provided [Research Problem] and [Original Solution], write a reference solution that describes the proposed method. The description must adhere to the following principles:

1. **Faithfulness**: Only describe content that is directly supported by the provided material. Do NOT add any fabricated details, speculative claims, or information not present in the inputs.
2. **No concrete experimental data**: Exclude all specific numerical results, statistics, or quantitative outcomes. Focus on the rationale and design logic of the method, not the raw numbers.
3. **Content focus**: Emphasize the principles and implementation of the proposed method, including the core technical innovation, key algorithmic steps, necessary constraints, and practical feasibility. Do NOT include experimental design details (e.g., baselines, datasets, evaluation metrics).
4. **Academic style**: Use formal, precise, and concise academic language. Write in a structured but paragraph-based flow — avoid bullet points, numbered lists, or section headers. Each sentence should convey a clear technical point.

# Output Format
Wrap the final reference solution inside <output> </output> tags. The content within the tags should be the solution only, without introductory phrases, conversational filler, or meta-commentary.

# Input
[Research Problem]:
{research_problem}

[Original Solution]:
{raw_solution}"""
    try:
        reference_solution = llm_client.generate_response(prompt, max_tokens=4096, temperature=0.3)
        if not reference_solution or not reference_solution.strip():
            return ""
        return clean_content_tags(reference_solution)
    except Exception as e:
        print(f"[Thread: {threading.get_ident()}] Error generating reference solution: {str(e)}", flush=True)
        return ""


def generate_rubrics_for_solution(llm_client: LLMClient, research_problem: str, reference_solution: str) -> List[Dict]:
    """
    Generate detailed, binary (true/false) evaluation rubrics for a proposed research solution.
    """
    prompt = f"""
# Role
You are an expert in scientific methodology and solution evaluation. Your task is to analyze the given research problem and reference solution, and generate comprehensive evaluation rubrics to assess the quality of any proposed solution in a binary (True/False) manner.

# Research Problem
{research_problem}

# Reference Solution
{reference_solution}

# Rubric Design Guidelines
Each rubric must be:
- **True/False binary**: objectively assessable without subjective interpretation.
- **Atomic**: evaluate ONE and only ONE independent concept per rubric.
- **Objective**: avoid subjective adjectives (good, detailed, clear, reasonable); use deterministic phrasing (e.g., "Contains formula X", "Mentions concept Y").
- **Negation-style positively phrased**: e.g., "No logical conflicts are present" rather than "Logical conflicts occurred".
- **Not about final results**: do NOT include rubrics that require executing experiments to verify.
- **Not about trivial details**: avoid minor/overly specific details of the reference solution, as multiple valid approaches may exist.

Construct rubrics focusing exclusively on the following dimension:

**Method Principles and Implementation**: Assess whether the solution correctly describes the core principles of the method, the technical implementation logic, key procedural steps, necessary constraints, practical feasibility, and the novelty of the proposed approach. Do NOT include rubrics related to experimental design, baselines, datasets, or evaluation metrics.

Prioritize rubrics that target the **core innovation points and key steps** of the solution's method — discard trivial or peripheral aspects. Fewer high-impact rubrics are better than many shallow ones.

# Output Requirements
Generate exactly 10 rubrics. Avoid overly specific numerical settings (e.g., learning rates, batch sizes, epochs). Provide strictly valid JSON.
Wrap the output JSON array in ```json ``` code blocks, formatted as:
```json
[
  {{"id": 1, "description": "..."}},
  {{"id": 2, "description": "..."}}
]
```"""
    
    try:
        rubrics_text = llm_client.generate_response(prompt, max_tokens=2048, temperature=0.2)
    except Exception as e:
        print(f"[ERROR Thread: {threading.get_ident()}] API call failed: {str(e)}", flush=True)
        return []
    
    # Try to parse the returned JSON text
    try:
        parsed_data = None
        # Optimization: fix the regex to match an array [...] rather than an object {...}
        json_match = re.search(r'```json\s*(\[.*?\])\s*```', rubrics_text, re.DOTALL)
        if json_match:
            json_str = json_match.group(1)
            parsed_data = json.loads(json_str)
        else:
            array_match = re.search(r'```\s*(\[.*?\])\s*```', rubrics_text, re.DOTALL)
            if array_match:
                json_str = array_match.group(1)
                parsed_data = json.loads(json_str)
            else:
                # Try to extract the first pair of square brackets in the whole text
                array_match = re.search(r'$$.*$$', rubrics_text, re.DOTALL)
                if array_match:
                    json_str = array_match.group(0)
                    parsed_data = json.loads(json_str)
        if parsed_data and isinstance(parsed_data, list):
            validated_rubrics = []
            for item in parsed_data:
                if isinstance(item, dict) and 'description' in item:
                    validated_rubrics.append({
                        'id': len(validated_rubrics) + 1,
                        'description': item['description'],
                        'weight': 1
                    })
            return validated_rubrics
        print(f"[WARNING] Failed to parse valid rubrics, returning empty list.", flush=True)
        return []
    except Exception as e:
        print(f"[ERROR] Error parsing rubrics: {str(e)}", flush=True)
        print(f"[DEBUG] Raw output: {rubrics_text}", flush=True)
        return []


