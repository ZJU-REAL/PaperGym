def merge_and_rank_rubrics(llm_client: LLMClient, rubric_list_a: List[Dict], rubric_list_b: List[Dict], research_problem: str, reference_solution: str) -> List[Dict]:
    """
    Merge two rubric lists by deduplicating semantically similar items and
    ranking the remaining rubrics by importance (high to low).
    Uses the reference solution as additional context to judge importance.
    Returns a new ranked list with re-assigned sequential IDs.
    """
    # Flatten both lists into arrays of description strings
    descriptions_a = [r['description'] for r in rubric_list_a if isinstance(r, dict) and 'description' in r]
    descriptions_b = [r['description'] for r in rubric_list_b if isinstance(r, dict) and 'description' in r]

    if not descriptions_a and not descriptions_b:
        return []

    prompt = f"""# Role
You are an expert in scientific evaluation methodology. Your task is to synthesize a definitive set of evaluation rubrics by merging two candidate lists.

# Task
You are provided with a [Research Problem], a [Reference Solution], and two sets of binary rubrics ([Set A] and [Set B]). Perform the following:

1. **Strategic Merging & Deduplication**: Identify rubrics that assess the same underlying technical criterion. When duplicates or semantic overlaps occur:
    - Select the single best version from the existing candidates that is most specific and measurable.
    - **Crucial**: You must pick one of the original strings. Do NOT synthesize new wording or paraphrase.
    - Remove all other redundant versions.

2. **Importance Ranking**: Rank the unique rubrics from high to low importance based on the [Reference Solution]:
    - **Top Tier**: Rubrics assessing the core novelty, theoretical breakthroughs, or critical technical steps.
    - **Lower Tier**: Rubrics assessing routine setup, standard metrics, or auxiliary experimental details.

# Research Problem
{research_problem}

# Reference Solution
{reference_solution}

# Rubric Set A (Derived from Ground-Truth)
{json.dumps([r['description'] for r in rubric_list_a], ensure_ascii=False) if rubric_list_a else "[]"}

# Rubric Set B (Derived from Problem Only)
{json.dumps([r['description'] for r in rubric_list_b], ensure_ascii=False) if rubric_list_b else "[]"}

# Output Requirements
- Output ONLY a valid JSON array of objects.
- Each object must follow this exact schema: {{"description": "string"}}.
- No other fields (id, weight, etc.) are allowed.
- No conversational filler, introductory text, or markdown formatting outside the JSON block.
- The order of elements in the array must reflect their importance (descending).

[
  {{"description": "..."}},
  ...
]"""

    try:
        response_text = llm_client.generate_response(prompt, max_tokens=2048, temperature=0.2)
    except Exception as e:
        print(f"[Thread: {threading.get_ident()}] Error merging rubrics: {str(e)}", flush=True)
        # Fall back: simply concatenate both lists
        combined = rubric_list_a + rubric_list_b
        for i, r in enumerate(combined):
            r['id'] = i + 1
        return combined

    # Parse the merged JSON
    try:
        json_match = re.search(r'```json\s*(\[.*?\])\s*```', response_text, re.DOTALL)
        if not json_match:
            array_match = re.search(r'\[.*\]', response_text, re.DOTALL)
            if array_match:
                json_str = array_match.group(0)
            else:
                raise ValueError("No JSON array found")
        else:
            json_str = json_match.group(1)

        parsed = json.loads(json_str)
        if not isinstance(parsed, list):
            raise ValueError("Parsed result is not a list")

        # Validate and re-assign IDs
        validated = []
        for item in parsed:
            if isinstance(item, dict) and 'description' in item and isinstance(item['description'], str):
                validated.append({
                    'id': len(validated) + 1,
                    'description': item['description'].strip(),
                    'weight': 1
                })

        if validated:
            print(f"[Thread: {threading.get_ident()}] Successfully merged and ranked {len(validated)} rubrics (from {len(descriptions_a)}+{len(descriptions_b)} inputs)", flush=True)
            return validated

        raise ValueError("No valid rubrics after validation")

    except Exception as e:
        print(f"[Thread: {threading.get_ident()}] Error parsing merged rubrics: {str(e)}", flush=True)
        # Fall back
        combined = rubric_list_a + rubric_list_b
        for i, r in enumerate(combined):
            r['id'] = i + 1
        return combined


def process_paper_batch(args):
    """
    Process a batch of papers with the given arguments
    """
    paper_batch, paper_dir, background_dir, output_dir, batch_idx, total_batches = args
    
    # Initialize a new LLM client for this thread
    llm_client = get_llm_client(
        model="Qwen3-235B-A22B",
        api_key=os.getenv("OPENSCIENCE_API_KEY", ""),
        base_url=os.getenv("OPENSCIENCE_BASE_URL", "http://your-api/v1")
        )

    # rubric_client = get_llm_client(
    #     model="Qwen3-235B-A22B",
    #     api_key=os.getenv("OPENSCIENCE_API_KEY", ""),
    #     base_url=os.getenv("OPENSCIENCE_BASE_URL", "http://your-api/v1")
    #     )
    rubric_client = get_llm_client(
        model="DeepSeek-V4-Flash",
        api_key=os.getenv("OPENSCIENCE_API_KEY", ""),
        base_url=os.getenv("OPENSCIENCE_BASE_URL", "http://your-api/v1")
        )
    
    processed_count = 0
    batch_size = len(paper_batch)
    
    thread_id = threading.get_ident()
    print(f"[Thread: {thread_id}] Starting batch {batch_idx+1}/{total_batches} with {batch_size} papers", flush=True)
    
    for i, paper in enumerate(paper_batch):
        filename = paper['filename']
        # Remove .tex extension for consistent naming
        filename_without_ext = os.path.splitext(filename)[0]
        print(f"[Thread: {thread_id}] Processing paper {i+1}/{batch_size} ({filename}) in batch {batch_idx+1}/{total_batches}", flush=True)
        
        # Construct paths for input and output files
        background_file = os.path.join(background_dir, f"{filename_without_ext}.json")
        output_file = os.path.join(output_dir, f"{filename_without_ext}.json")
        
        # Load background result (pre-filter already ensures file exists, but keep for safety)
        try:
            with open(background_file, 'r', encoding='utf-8') as f:
                bg_result = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError) as e:
            print(f"[Thread: {thread_id}] Skipping {filename} due to background file error: {e}", flush=True)
            continue
        
        try:
            # Step 1: Get research field, research background and solution directly from background result
            research_field = bg_result.get('research_field', '')
            research_background = bg_result.get('research_background', '')
            
            if not research_field:
                print(f"[Thread: {thread_id}] Warning: No research field found for {filename}, skipping...", flush=True)
                continue
                
            if not research_background:
                print(f"[Thread: {thread_id}] Warning: No research background found for {filename}, skipping...", flush=True)
                continue
            
            # Step 2: Construct and condense research problem based on extracted field and background
            research_problem = construct_research_problem(llm_client, research_field, research_background)
            if not research_problem:
                print(f"[Thread: {thread_id}] Warning: Failed to construct research problem for {filename}, skipping...", flush=True)
                continue

            # Reference answer directly from background file
            raw_solution = bg_result.get('solution', '')
            if not raw_solution:
                print(f"[Thread: {thread_id}] Warning: No solution found for {filename}, skipping...", flush=True)
                continue

            # Step 3: Generate refined reference solution (based on original solution only, no experiment)
            reference_solution = generate_reference_solution(llm_client, research_problem, raw_solution)
            if not reference_solution:
                print(f"[Thread: {thread_id}] Warning: Failed to generate reference solution for {filename}, skipping...", flush=True)
                continue

            # Step 4: Generate rubrics for the solution
            rubric_for_solution = generate_rubrics_for_solution(rubric_client, research_problem, reference_solution)
            if len(rubric_for_solution) < 3:
                print(f"[Thread: {thread_id}] Warning: Insufficient number of solution-rubrics ({len(rubric_for_solution)}) generated for {filename}, skipping...", flush=True)
                continue

            # Step 5: Generate rubrics for the problem
            rubric_for_problem = generate_rubrics_for_problem(rubric_client, research_problem)
            if len(rubric_for_problem) < 3:
                print(f"[Thread: {thread_id}] Warning: Insufficient number of problem-rubrics ({len(rubric_for_problem)}) generated for {filename}, skipping...", flush=True)
                continue

            # Step 6: Merge and rank rubrics from both sources
            merged_rubrics = merge_and_rank_rubrics(rubric_client, rubric_for_solution, rubric_for_problem, research_problem, reference_solution)
            if len(merged_rubrics) < 3:
                print(f"[Thread: {thread_id}] Warning: Too few rubrics ({len(merged_rubrics)}) after merging for {filename}, skipping...", flush=True)
                continue

            # Step 7: Store the data
            solution_pair = {
                "filename": filename,
                "research_question": research_problem,
                "reference_answer": reference_solution,
                "solution_rubrics": rubric_for_solution,
                "problem_rubrics": rubric_for_problem,
                "merged_rubrics": merged_rubrics,
                "rubrics": merged_rubrics[:10],
                "research_field": research_field,
                "research_background": research_background
            }
            
            # Save to individual output file
            with open(output_file, 'w', encoding='utf-8') as f:
                json.dump(solution_pair, f, ensure_ascii=False, indent=2)
            
            print(f"[Thread: {thread_id}]: Saved solution to {output_file}", flush=True)
            processed_count += 1
        except Exception as e:
            print(f"[Thread: {thread_id}] Error processing {filename}: {str(e)}", flush=True)
            # Skip to the next paper
            continue
    
    print(f"[Thread: {thread_id}] Completed batch {batch_idx+1}/{total_batches}, processed {processed_count} papers", flush=True)
    return processed_count


def process_papers_to_solution_pairs_parallel(
    background_dir: str = "/path/to/research_background",
    paper_dir: str = "/path/to/paper_bodies_latex",
    output_dir: str = "/path/to/method_results",
    num_threads: int = None,
    max_papers: int = 0
):
    """
    Main function to process papers in parallel and generate solution-answer pairs with rubrics
    Papers are divided into groups and processed in parallel threads.
    
    Args:
        max_papers: Maximum number of papers to process. 0 or None means process all.
    """
    if num_threads is None:
        num_threads = 4  # Reasonable default for API-bound tasks

    # Read paper filenames (no need to load file content)
    papers = [{'filename': f} for f in os.listdir(paper_dir) if f.endswith('.tex')]

    if not papers:
        print("No papers found to process.", flush=True)
        return 0

    # Truncate to max_papers if specified
    if max_papers:
        papers = papers[:max_papers]

    # Pre-filter: remove papers that already have output or lack background file
    pre_filter_count = 0
    filtered_papers = []
    for paper in papers:
        filename_without_ext = os.path.splitext(paper['filename'])[0]
        output_file = os.path.join(output_dir, f"{filename_without_ext}.json")
        background_file = os.path.join(background_dir, f"{filename_without_ext}.json")

        if os.path.exists(output_file):
            pre_filter_count += 1
            continue
        if not os.path.exists(background_file):
            pre_filter_count += 1
            continue

        filtered_papers.append(paper)

    papers = filtered_papers
    if pre_filter_count > 0:
        print(f"Pre-filter: skipped {pre_filter_count} papers (already processed or missing background), remaining: {len(papers)}", flush=True)

    if not papers:
        print("No papers remaining after pre-filtering.", flush=True)
        return 0

    # Create output directory if it doesn't exist
    os.makedirs(output_dir, exist_ok=True)
    
    # Determine actual number of threads to use based on number of papers
    actual_num_threads = min(num_threads, len(papers))
    
    # Split papers into exactly 'actual_num_threads' batches for parallel processing
    # Each thread will handle one batch
    num_papers_per_batch = len(papers) // actual_num_threads
    remainder = len(papers) % actual_num_threads
    
    paper_batches = []
    start_idx = 0
    for i in range(actual_num_threads):
        # Distribute remainder papers evenly among the first 'remainder' batches
        end_idx = start_idx + num_papers_per_batch + (1 if i < remainder else 0)
        paper_batches.append(papers[start_idx:end_idx])
        start_idx = end_idx
    
    # Prepare arguments for each thread
    thread_args = [
        (batch, paper_dir, background_dir, output_dir, idx, len(paper_batches))
        for idx, batch in enumerate(paper_batches)
    ]
    
    print(f"Starting parallel processing with {actual_num_threads} threads for {len(papers)} papers in {len(paper_batches)} batches...", flush=True)
    
    # Use ThreadPoolExecutor to process batches in parallel
    with ThreadPoolExecutor(max_workers=actual_num_threads) as executor:
        # Submit all tasks to the thread pool
        futures = [executor.submit(process_paper_batch, arg) for arg in thread_args]
        
        # Collect results as they complete
        results = [future.result() for future in futures]
    
    total_processed = sum(results)
    
    print(f"Parallel processing completed. Total papers processed: {total_processed}", flush=True)
    return total_processed


def process_papers_to_solution_pairs(
    background_dir: str = "/path/to/research_background",
    paper_dir: str = "/path/to/paper_bodies_latex",
    output_dir: str = "/path/to/method_results",
    max_papers: int = 0
):
    # Call the parallel version with default settings
    return process_papers_to_solution_pairs_parallel(background_dir, paper_dir, output_dir, max_papers=max_papers)

