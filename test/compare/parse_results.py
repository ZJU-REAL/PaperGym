#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
parse_results.py — Parse the evaluation results generated by compare_responses.py (lite version).

Only outputs the core information:
  1. For each file pair: average Overall Score, Overall Score Win Rate, and per-dimension Win Rate;
  2. Overall summary across all file pairs (each model's average score + Win Rate).

Win Rate definition: wins / (wins + losses + ties)

Usage:
  python3 parse_results.py [result directory]
"""

import json
import os
import sys
import glob
import argparse
from collections import defaultdict

DIMENSIONS = [
    "goal_alignment",
    "novel_insight",
    "scientific_soundness",
    "execution_quality",
    "expected_impact",
]

# Short names for dimensions (for compact display)
DIM_LABELS = {
    "goal_alignment": "GoalAlign",
    "novel_insight": "Novelty",
    "scientific_soundness": "Soundness",
    "execution_quality": "ExecQual",
    "expected_impact": "Impact",
}


def short_name(name: str) -> str:
    """Strip the _responses.json suffix to show a shorter model name."""
    return name.replace("_responses.json", "")


def load_results(result_dir):
    """Load all *_comparison_results.json in the directory, returning [(pair_name, results)]."""
    files = sorted(glob.glob(os.path.join(result_dir, "*_comparison_results.json")))
    pairs = []
    for fp in files:
        pair_name = os.path.basename(fp).replace("_comparison_results.json", "")
        try:
            with open(fp, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, list):
                pairs.append((pair_name, data))
            else:
                print(f"  [Warning] {fp} is not a list, skipped", file=sys.stderr)
        except (json.JSONDecodeError, IOError) as e:
            print(f"  [Warning] Could not load {fp}: {e}", file=sys.stderr)
    return pairs


def win_rate(wins, losses, ties):
    denom = wins + losses + ties
    return (wins / denom * 100.0) if denom > 0 else 0.0


def analyze_pair(pair_name, results):
    """Analyze a single file pair, returning a statistics dictionary."""
    total = len(results)
    valid = [r for r in results if r.get("parsed")]
    skipped = total - len(valid)
    if skipped > 0:
        print(f"  [Info] {pair_name}: {skipped}/{total} items have no valid parsed field, skipped",
              file=sys.stderr)
    if not valid:
        return None

    fa = valid[0]["file_a"]
    fb = valid[0]["file_b"]

    # Per-dimension wins/losses (counted by actual source file)
    dim_counts = {
        d: {fa: 0, fb: 0, "Tie": 0, "ParseError": 0}
        for d in DIMENSIONS
    }

    # Overall Score statistics (counted by actual source file)
    total_a = 0.0
    total_b = 0.0
    score_count = 0
    a_wins = 0
    b_wins = 0
    ties = 0

    for r in valid:
        parsed = r["parsed"]
        swapped = r.get("swapped", False)
        src_a = r["plan_a_actual_source"]
        src_b = r["plan_b_actual_source"]

        for d in DIMENSIONS:
            j = parsed.get(d, "ParseError")
            if j == "A":
                dim_counts[d][src_a] += 1
            elif j == "B":
                dim_counts[d][src_b] += 1
            elif j == "Tie":
                dim_counts[d]["Tie"] += 1
            else:
                dim_counts[d]["ParseError"] += 1

        try:
            sa = float(parsed.get("overall_score_a", 0))
            sb = float(parsed.get("overall_score_b", 0))
            if swapped:
                sa, sb = sb, sa
            total_a += sa
            total_b += sb
            score_count += 1
            if sa > sb:
                a_wins += 1
            elif sb > sa:
                b_wins += 1
            else:
                ties += 1
        except (ValueError, TypeError):
            pass

    return {
        "pair_name": pair_name,
        "fa": fa,
        "fb": fb,
        "valid_count": len(valid),
        "dim_counts": dim_counts,
        "avg_a": total_a / score_count if score_count else 0.0,
        "avg_b": total_b / score_count if score_count else 0.0,
        "score_count": score_count,
        "a_wins": a_wins,
        "b_wins": b_wins,
        "ties": ties,
    }


def print_pair(stat):
    fa, fb = stat["fa"], stat["fb"]
    sa, sb = short_name(fa), short_name(fb)
    print(f"\n{'='*70}")
    print(f"File pair: {stat['pair_name']}")
    print(f"  A = {fa}")
    print(f"  B = {fb}")
    print(f"  Valid items: {stat['valid_count']}")
    print(f"{'='*70}")

    if stat["score_count"] == 0:
        print("  No valid overall score")
        return

    # Scores
    print("\n  [Score] Average overall score")
    print(f"    {sa:<28} {stat['avg_a']:.2f}")
    print(f"    {sb:<28} {stat['avg_b']:.2f}")
    print(f"    Difference (A - B): {stat['avg_a'] - stat['avg_b']:+.2f}")

    # Overall wins/losses
    wa = win_rate(stat["a_wins"], stat["b_wins"], stat["ties"])
    wb = win_rate(stat["b_wins"], stat["a_wins"], stat["ties"])
    tie_ratio = stat["ties"] / stat["score_count"] * 100
    print("\n  [Win/Loss] Overall score win rate")
    print(f"    {sa:<28} {wa:6.1f}%")
    print(f"    {sb:<28} {wb:6.1f}%")
    print(f"    {'Tie':<28} {stat['ties']} items ({tie_ratio:.1f}%)")

    # Per-dimension wins/losses (three rows: A win rate / B win rate / Tie rate)
    parts_a = []
    parts_b = []
    parts_tie = []
    for d in DIMENSIONS:
        c = stat["dim_counts"][d]
        denom = c[fa] + c[fb] + c["Tie"]
        parts_a.append(f"{DIM_LABELS[d]} {win_rate(c[fa], c[fb], c['Tie']):.0f}%")
        parts_b.append(f"{DIM_LABELS[d]} {win_rate(c[fb], c[fa], c['Tie']):.0f}%")
        tie_r = (c["Tie"] / denom * 100.0) if denom > 0 else 0.0
        parts_tie.append(f"{DIM_LABELS[d]} {tie_r:.0f}%")
    print("\n  [Dimensions] Win rate per dimension:")
    print(f"    {sa:<16} " + " | ".join(parts_a))
    print(f"    {sb:<16} " + " | ".join(parts_b))
    print(f"    {'Tie':<16} " + " | ".join(parts_tie))


def merge_pair(stat, agg):
    """Merge a single pair's statistics into the overall aggregate."""
    for m, avg, wins, losses, ties in (
        (stat["fa"], stat["avg_a"], stat["a_wins"], stat["b_wins"], stat["ties"]),
        (stat["fb"], stat["avg_b"], stat["b_wins"], stat["a_wins"], stat["ties"]),
    ):
        s = agg["score"][m]
        s["total"] += avg * stat["score_count"]
        s["count"] += stat["score_count"]
        s["wins"] += wins
        s["losses"] += losses
        s["ties"] += ties


def print_aggregate(agg):
    print(f"\n\n{'#'*70}")
    print("# Overall summary (across all file pairs)")
    print(f"{'#'*70}")

    rows = []
    for m, s in agg["score"].items():
        if s["count"] == 0:
            continue
        avg = s["total"] / s["count"]
        wr = win_rate(s["wins"], s["losses"], s["ties"])
        rows.append((short_name(m), avg, wr, s["count"]))

    if not rows:
        print("  No valid data")
        return

    rows.sort(key=lambda x: -x[1])
    colw = max(len(r[0]) for r in rows) + 2
    print(f"\n  {'Model':<{colw}} {'Avg Score':>8} {'Win Rate':>10} {'Items':>6}")
    print(f"  {'-' * (colw + 28)}")
    for name, avg, wr, cnt in rows:
        print(f"  {name:<{colw}} {avg:>8.2f} {wr:>9.1f}% {cnt:>6}")


def main():
    parser = argparse.ArgumentParser(description="Parse evaluation results (compact version)")
    default_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
    parser.add_argument("result_dir", nargs="?", default=default_dir,
                        help="Results directory (default: results/ next to this script)")
    args = parser.parse_args()

    result_dir = args.result_dir
    if not os.path.isdir(result_dir):
        print(f"Error: directory does not exist: {result_dir}", file=sys.stderr)
        sys.exit(1)

    pairs = load_results(result_dir)
    if not pairs:
        print(f"No *_comparison_results.json found in {result_dir}", file=sys.stderr)
        sys.exit(1)

    print(f"Loaded results for {len(pairs)} file pairs from: {result_dir}")

    agg = {
        "score": defaultdict(lambda: {"total": 0.0, "count": 0,
                                      "wins": 0, "losses": 0, "ties": 0}),
    }

    for pair_name, results in pairs:
        stat = analyze_pair(pair_name, results)
        if stat is None:
            print(f"\n[Skip] {pair_name}: no valid results", file=sys.stderr)
            continue
        print_pair(stat)
        merge_pair(stat, agg)

    print_aggregate(agg)


if __name__ == "__main__":
    main()
