#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
compare_scoring_models.py — Compare the stability and scores of multiple scoring models
on the same dataset.

Reads answer/stablility/stability/<model>/summary.json (generated by stability_eval.py)
and aggregates metrics for each scoring model — overall mean, between-round std,
per-sample std, rubric agreement rate, category scores, etc. — into a comparison table,
and outputs cross-model difference statistics.

Usage:
    python compare_scoring_models.py                              # scan all models in the default directory
    python compare_scoring_models.py --models qwen3_4b kimi_k2_6  # compare only the specified models
    python compare_scoring_models.py --base-dir answer/stablility/stability
"""

import argparse
import json
import os

import numpy as np

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
# Use a relative path based on the script directory
DEFAULT_BASE_DIR = os.path.join(SCRIPT_DIR, "answer", "stablility", "stability")
KEY_METRICS = [
    ("overall_mean", "overall_mean"),
    ("overall_std", "overall_std"),
    ("round_std", "round_std"),
    ("round_range", "round_range"),
    ("mean_item_std", "mean_item_std"),
    ("pct_stable_items", "pct_stable_items"),
    ("rubric_agreement_rate", "rubric_agreement_rate"),
    ("n_rubric_pairs", "n_rubric_pairs"),
]


def discover_models(base_dir: str) -> list:
    """Scan all subdirectories under base_dir that contain a summary.json."""
    models = []
    if not os.path.isdir(base_dir):
        return models
    for name in sorted(os.listdir(base_dir)):
        sub = os.path.join(base_dir, name)
        if os.path.isdir(sub) and os.path.isfile(os.path.join(sub, "summary.json")):
            models.append(name)
    return models


def load_summary(base_dir: str, model: str) -> dict:
    with open(os.path.join(base_dir, model, "summary.json"), encoding="utf-8") as fh:
        return json.load(fh)


def fmt(v) -> str:
    if v is None:
        return "N/A"
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def main() -> None:
    p = argparse.ArgumentParser(description="Cross-scoring-model stability and score comparison")
    p.add_argument("--base-dir", "-d", default=DEFAULT_BASE_DIR,
                   help="Root directory containing each model's summary.json")
    p.add_argument("--models", "-m", nargs="+", default=None,
                   help="Model subdirectory names to compare; defaults to scanning all")
    p.add_argument("--out", "-o", default=None,
                   help="Output JSON path for the comparison result (default: print to terminal)")
    args = p.parse_args()

    models = args.models or discover_models(args.base_dir)
    if not models:
        print(f"[ERROR] no summary.json found under {args.base_dir}")
        return

    summaries = {m: load_summary(args.base_dir, m) for m in models}

    # ---- Table printing ----
    w_name = max(len(m) for m in models)
    header = f"{'Metric':<22}" + "".join(f"{m:>{w_name+6}}" for m in models)
    print("=" * len(header))
    print(header)
    print("=" * len(header))

    table_rows = {}
    for key, label in KEY_METRICS:
        row = f"{label:<22}"
        vals = []
        for m in models:
            v = summaries[m].get(key)
            row += f"{fmt(v):>{w_name+6}}"
            if v is not None:
                vals.append(v)
        table_rows[key] = vals
        print(row)

    # Category mean scores
    for cat in ["cs", "econ", "physics"]:
        row = f"category-{cat:<18}"
        vals = []
        for m in models:
            v = summaries[m].get("category_mean", {}).get(cat)
            row += f"{fmt(v):>{w_name+6}}"
            if v is not None:
                vals.append(v)
        table_rows[f"category_mean/{cat}"] = vals
        print(row)

    print("=" * len(header))

    # Per-round mean scores
    print("\nPer-round mean scores (round_means):")
    for m in models:
        rms = summaries[m].get("round_means", [])
        print(f"  {m:<{w_name}}: " + ", ".join(f"{x:.4f}" for x in rms))

    # ---- Cross-model difference statistics ----
    print("\n--- Cross-model difference statistics ---")
    for key, label in KEY_METRICS:
        vals = table_rows[key]
        if len(vals) >= 2 and all(v is not None for v in vals):
            arr = np.array(vals, dtype=float)
            print(f"  {label}: cross-model min={arr.min():.4f} max={arr.max():.4f} "
                  f"range={arr.max()-arr.min():.4f} (max-min)")

    # Pairwise overall-mean differences between models
    print("\nPairwise overall-mean differences:")
    for i in range(len(models)):
        for j in range(i + 1, len(models)):
            a, b = summaries[models[i]].get("overall_mean"), summaries[models[j]].get("overall_mean")
            if a is not None and b is not None:
                print(f"  {models[i]} vs {models[j]}: |{a:.4f} - {b:.4f}| = {abs(a-b):.4f}")

    # Save JSON
    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            json.dump({"models": models, "summaries": summaries}, fh,
                      ensure_ascii=False, indent=2)
        print(f"\nComparison result saved to: {args.out}")


if __name__ == "__main__":
    main()
