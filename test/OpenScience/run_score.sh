#!/bin/bash
#
# Batch scoring: scores all answer JSON files under answer/<FOLDER>/ using rubrics.
#
# Usage:
#   1. First generate answers (run_generate.sh), making sure JSON answer files exist under answer/<FOLDER>/
#   2. bash run_score.sh                  # uses the default folder innov
#   3. bash run_score.sh innov          # specify a single folder
#   4. bash run_score.sh innov design   # specify multiple folders (processed in order)

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# ========== Configuration parameters ==========

# ---- The list of folders to process ----
if [[ $# -eq 0 ]]; then
    FOLDERS=("innov")
else
    FOLDERS=("$@")
fi

MAX_ITEMS=1200

# ---- Scoring model configuration (remote API or local vLLM) ----
SCORE_BASE_URL="http://xxx"
SCORE_API_KEY="sk-xxx"
SCORE_MODEL="DeepSeek-V4-Flash"

# ---- Concurrency ----
NUM_WORKERS=15

# ---- Only score these answer files (empty = score all) ----
# SCORE_ANSWERS=("xxx.json")

# ========== Signal handling ==========

PYTHON_PID=""

cleanup() {
    echo ""
    echo "Signal received, terminating the scoring process..."
    if [[ -n $PYTHON_PID ]] && kill -0 "$PYTHON_PID" 2>/dev/null; then
        # First terminate the whole process tree (python may have started child threads/processes)
        local child_pids
        child_pids=$(pgrep -P "$PYTHON_PID" 2>/dev/null || true)
        kill -TERM "$PYTHON_PID" 2>/dev/null
        for cpid in $child_pids; do
            kill -TERM "$cpid" 2>/dev/null || true
        done
        sleep 2
        if kill -0 "$PYTHON_PID" 2>/dev/null; then
            kill -KILL "$PYTHON_PID" 2>/dev/null
            for cpid in $child_pids; do
                kill -KILL "$cpid" 2>/dev/null || true
            done
        fi
    fi
    exit 1
}

trap cleanup SIGTERM SIGINT SIGQUIT SIGHUP

# ========== Score folder by folder ==========

for FOLDER in "${FOLDERS[@]}"; do

    # ---- Dataset ----
    PARQUET_PATH="${SCRIPT_DIR}/data/${FOLDER}.parquet"
    # PARQUET_PATH="${SCRIPT_DIR}/data/experiment_mini.parquet"

    # ---- Answer directory (generated by run_generate.sh) ----
    ANSWER_DIR="${SCRIPT_DIR}/answer/${FOLDER}"

    # ---- Scoring result output directory ----
    SCORE_DIR="${SCRIPT_DIR}/score/${FOLDER}"

    # ---- Check whether the dataset exists ----
    if [[ ! -f "$PARQUET_PATH" ]]; then
        echo "[Error] Dataset does not exist: ${PARQUET_PATH}, skipping folder ${FOLDER}"
        continue
    fi

    # ---- Check whether the answer directory exists ----
    if [[ ! -d "$ANSWER_DIR" ]]; then
        echo "[Error] Answer directory does not exist: ${ANSWER_DIR}, skipping folder ${FOLDER}"
        echo "Please run run_generate.sh first to generate answers"
        continue
    fi

    # ---- Collect all JSON answer files ----
    ANSWER_FILES=()
    while IFS= read -r -d '' f; do
        ANSWER_FILES+=("$f")
    done < <(find "$ANSWER_DIR" -maxdepth 1 -name '*.json' -print0)

    if [[ ${#ANSWER_FILES[@]} -eq 0 ]]; then
        echo "[Error] No JSON answer files found under ${ANSWER_DIR}, skipping folder ${FOLDER}"
        continue
    fi

    # Only score the whitelisted answer files (when SCORE_ANSWERS is non-empty)
    if [[ ${#SCORE_ANSWERS[@]} -gt 0 ]]; then
        filtered=()
        for f in "${ANSWER_FILES[@]}"; do
            for pat in "${SCORE_ANSWERS[@]}"; do
                if [[ "$(basename "$f")" == "$pat" ]]; then
                    filtered+=("$f")
                    break
                fi
            done
        done
        ANSWER_FILES=("${filtered[@]}")
    fi

    if [[ ${#ANSWER_FILES[@]} -eq 0 ]]; then
        echo "[Error] No answer files left to score after whitelist filtering, skipping folder ${FOLDER}"
        continue
    fi

    # ========== Summary information ==========

    echo ""
    echo "==========================================="
    echo "  Batch scoring"
    echo "  Folder:          ${FOLDER}"
    echo "  Dataset:         ${PARQUET_PATH}"
    echo "  Answer dir:      ${ANSWER_DIR}"
    echo "  Files to score:  ${#ANSWER_FILES[@]}"
    echo "  Judge model:     ${SCORE_MODEL}"
    echo "  API:        ${SCORE_BASE_URL}"
    echo "  Items:           ${MAX_ITEMS}"
    echo "  Output dir:      ${SCORE_DIR}"
    echo "==========================================="

    for answer_file in "${ANSWER_FILES[@]}"; do
        basename=$(basename "$answer_file")
        echo "  - ${basename}"
    done

    echo ""

    # ========== Score one by one ==========

    for answer_file in "${ANSWER_FILES[@]}"; do
        # Extract the file name (without path and extension) to construct the output path
        base_name=$(basename "$answer_file" .json)
        output_file="${SCORE_DIR}/${base_name}_scores.json"

        echo ""
        echo "==========================================="
        echo "  Scoring:     ${base_name}"
        echo "  Answer file: ${answer_file}"
        echo "  Output file: ${output_file}"
        echo "==========================================="

        # Create the output directory
        mkdir -p "$(dirname "$output_file")"

        echo ""
        echo ">>> Starting scoring (${NUM_WORKERS} threads)..."
        echo ""

        python -u "$SCRIPT_DIR/score_responses.py" \
            --parquet_path "$PARQUET_PATH" \
            --answer_path "$answer_file" \
            --output_path "$output_file" \
            --num_workers "$NUM_WORKERS" \
            --max_items "$MAX_ITEMS" \
            --api_key "$SCORE_API_KEY" \
            --base_url "$SCORE_BASE_URL" \
            --model "$SCORE_MODEL" &
        PYTHON_PID=$!
        wait "$PYTHON_PID" || true
        PYTHON_PID=""
    done

    echo ""
    echo "==========================================="
    echo "  Folder scoring completed: ${FOLDER}"
    echo "  Output dir: ${SCORE_DIR}"
    echo "==========================================="
    echo ""
    echo "Generated files:"
    for answer_file in "${ANSWER_FILES[@]}"; do
        base_name=$(basename "$answer_file" .json)
        echo "  - ${SCORE_DIR}/${base_name}_scores.json"
    done
    echo ""

done

echo ""
echo "==========================================="
echo "  Scoring completed for all folders"
echo "  Folders processed: ${FOLDERS[*]}"
echo "==========================================="
echo ""
